CREATE OR REPLACE FUNCTION public.add_debt_payment(p_debt_id bigint, p_amount numeric, p_date date, p_wallet_id bigint DEFAULT NULL::bigint)
 RETURNS bigint
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_user uuid := auth.uid();
  v_debt debts%rowtype;
  v_into_wallet boolean;
  v_trx_id bigint;
  v_payment_id bigint;
  v_new_remaining numeric;
begin
  if v_user is null then
    raise exception 'Sesi login berakhir. Silakan masuk lagi.';
  end if;

  select * into v_debt from debts where id = p_debt_id and user_id = v_user for update;
  if not found then
    raise exception 'Utang tidak ditemukan.';
  end if;
  if v_debt.remaining_amount <= 0 then
    raise exception 'Utang ini sudah lunas!';
  end if;
  if p_amount is null or p_amount <= 0 then
    raise exception 'Nominal harus lebih dari 0.';
  end if;
  if p_amount > v_debt.remaining_amount then
    raise exception 'Jumlah bayar tidak boleh melebihi sisa utang!';
  end if;
  if p_date is null then
    raise exception 'Tanggal pembayaran wajib diisi.';
  end if;
  if p_date < v_debt.loan_date then
    raise exception 'Tanggal bayar tidak boleh sebelum tanggal pinjam.';
  end if;
  if p_date > current_date + 1 then
    raise exception 'Tanggal bayar tidak boleh di masa depan.';
  end if;

  v_into_wallet := (v_debt.type = 'receivable');

  if p_wallet_id is not null then
    perform debt_move_wallet(
      p_wallet_id,
      case when v_into_wallet then p_amount else -p_amount end,
      'Saldo dompet tidak mencukupi!'
    );

    insert into transactions (user_id, wallet_id, category_id, amount, date, note)
    values (
      v_user, p_wallet_id, debt_category_id(not v_into_wallet), p_amount, p_date,
      case when v_into_wallet then 'Menerima bayaran dari ' else 'Bayar utang ke ' end
        || v_debt.name || ' [DEBT_ID:' || v_debt.id || ']'
    )
    returning id into v_trx_id;
  end if;

  insert into debt_payments (debt_id, user_id, wallet_id, amount, date, transaction_id)
  values (v_debt.id, v_user, p_wallet_id, p_amount, p_date, v_trx_id)
  returning id into v_payment_id;

  v_new_remaining := v_debt.remaining_amount - p_amount;
  update debts
  set remaining_amount = v_new_remaining,
      status = case when v_new_remaining <= 0 then 'paid' else 'active' end
  where id = v_debt.id;

  return v_payment_id;
end $function$
;

CREATE OR REPLACE FUNCTION public.buy_investment(p_name text, p_type text, p_amount numeric, p_wallet_id bigint, p_date date)
 RETURNS bigint
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_user uuid := auth.uid();
  v_id bigint;
begin
  if v_user is null then raise exception 'Sesi login berakhir. Silakan masuk lagi.'; end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Semua kolom wajib diisi!'; end if;
  perform lock_wallet_with_balance(p_wallet_id, p_amount, 'Saldo dompet tidak mencukupi!');
  insert into investments (user_id, name, type, capital_amount, current_value)
  values (v_user, p_name, p_type, p_amount, p_amount) returning id into v_id;
  insert into transactions (user_id, wallet_id, category_id, amount, date, note)
  values (v_user, p_wallet_id, system_category('%Investasi%', 'Investasi', true, 'chart-line-up'),
          p_amount, p_date, 'Beli Aset: ' || p_name);
  perform wallet_add(p_wallet_id, -p_amount);
  return v_id;
end $function$
;

CREATE OR REPLACE FUNCTION public.buy_sell_investment(p_investment_id bigint, p_is_buy boolean, p_amount numeric, p_wallet_id bigint, p_date date)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_user uuid := auth.uid();
  v_inv investments%rowtype;
begin
  if v_user is null then raise exception 'Sesi login berakhir. Silakan masuk lagi.'; end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Nominal tidak boleh kosong!'; end if;
  select * into v_inv from investments where id = p_investment_id and user_id = v_user for update;
  if not found then raise exception 'Aset investasi tidak ditemukan.'; end if;
  if p_is_buy then
    perform lock_wallet_with_balance(p_wallet_id, p_amount, 'Saldo dompet tidak mencukupi!');
  else
    if p_amount > coalesce(v_inv.current_value, 0) then
      raise exception 'Nominal penarikan melebihi nilai aset saat ini!';
    end if;
    perform lock_wallet_with_balance(p_wallet_id, 0, '');
  end if;

  update investments set
    capital_amount = case when p_is_buy then capital_amount + p_amount else greatest(capital_amount - p_amount, 0) end,
    current_value = case when p_is_buy then current_value + p_amount else greatest(current_value - p_amount, 0) end
  where id = v_inv.id;
  insert into transactions (user_id, wallet_id, category_id, amount, date, note)
  values (v_user, p_wallet_id,
          case when p_is_buy then system_category('%Investasi%', 'Investasi', true, 'chart-line-up')
               else system_category('%Hasil Jual Investasi%', 'Hasil Jual Investasi', false, 'chart-line-up') end,
          p_amount, p_date,
          case when p_is_buy then 'Top Up Aset: ' else 'Jual Aset: ' end || v_inv.name);
  perform wallet_add(p_wallet_id, case when p_is_buy then -p_amount else p_amount end);
end $function$
;

CREATE OR REPLACE FUNCTION public.create_debt(p_name text, p_type text, p_amount numeric, p_loan_date date, p_due_date date DEFAULT NULL::date, p_notes text DEFAULT NULL::text, p_wallet_id bigint DEFAULT NULL::bigint)
 RETURNS bigint
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_user uuid := auth.uid();
  v_name text := trim(coalesce(p_name, ''));
  v_into_wallet boolean := (p_type = 'payable');
  v_debt_id bigint;
  v_trx_id bigint;
begin
  if v_user is null then
    raise exception 'Sesi login berakhir. Silakan masuk lagi.';
  end if;
  if v_name = '' then
    raise exception 'Nama tidak boleh kosong!';
  end if;
  if p_type is null or p_type not in ('payable', 'receivable') then
    raise exception 'Jenis utang tidak dikenal.';
  end if;
  if p_amount is null or p_amount <= 0 then
    raise exception 'Nominal harus lebih dari 0.';
  end if;
  if p_loan_date is null then
    raise exception 'Tanggal pinjam wajib diisi.';
  end if;
  if p_loan_date > current_date + 1 then
    raise exception 'Tanggal pinjam tidak boleh di masa depan.';
  end if;

  insert into debts (user_id, name, type, amount, remaining_amount, loan_date, due_date, notes, status, wallet_id)
  values (v_user, v_name, p_type, p_amount, p_amount, p_loan_date, p_due_date,
          nullif(trim(coalesce(p_notes, '')), ''), 'active', p_wallet_id)
  returning id into v_debt_id;

  if p_wallet_id is not null then
    perform debt_move_wallet(
      p_wallet_id,
      case when v_into_wallet then p_amount else -p_amount end,
      'Saldo dompet tidak mencukupi untuk dipinjamkan!'
    );

    insert into transactions (user_id, wallet_id, category_id, amount, date, note)
    values (
      v_user, p_wallet_id, debt_category_id(not v_into_wallet), p_amount, p_loan_date,
      case when v_into_wallet then 'Pinjaman diterima dari ' else 'Memberi pinjaman ke ' end
        || v_name || ' [DEBT_ID:' || v_debt_id || ']'
    )
    returning id into v_trx_id;

    update debts set transaction_id = v_trx_id where id = v_debt_id;
  end if;

  return v_debt_id;
end $function$
;

CREATE OR REPLACE FUNCTION public.debt_category_id(p_is_expense boolean)
 RETURNS bigint
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_user uuid := auth.uid();
  v_name text := case when p_is_expense
    then 'Sistem: Uang Keluar (Utang/Piutang)'
    else 'Sistem: Uang Masuk (Utang/Piutang)' end;
  v_id bigint;
begin
  if v_user is null then
    raise exception 'Sesi login berakhir. Silakan masuk lagi.';
  end if;

  select id into v_id
  from categories
  where user_id = v_user and name = v_name and is_expense = p_is_expense
  order by id
  limit 1;

  if v_id is null then
    insert into categories (user_id, name, is_expense, icon_name)
    values (v_user, v_name, p_is_expense, 'bank')
    returning id into v_id;
  end if;

  return v_id;
end $function$
;

CREATE OR REPLACE FUNCTION public.debt_move_wallet(p_wallet_id bigint, p_delta numeric, p_insufficient_msg text)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
begin
  perform wallet_spend_guard(p_wallet_id, greatest(-p_delta, 0),
    case when p_insufficient_msg like '%Hapus saja%'
         then ' Pilih "Hapus saja" bila uangnya sudah terpakai.' else '' end);
  update wallets set balance = coalesce(balance, 0) + p_delta where id = p_wallet_id;
end $function$
;

CREATE OR REPLACE FUNCTION public.delete_debt(p_debt_id bigint, p_refund boolean DEFAULT false)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_user uuid := auth.uid();
  v_debt debts%rowtype;
  v_pay record;
  v_trx_ids bigint[];
  v_msg text := 'Saldo dompet tidak mencukupi untuk mengembalikan saldo utang ini! Pilih "Hapus saja" bila uangnya sudah terpakai.';
  v_loan_live boolean;
begin
  if v_user is null then
    raise exception 'Sesi login berakhir. Silakan masuk lagi.';
  end if;

  select * into v_debt from debts where id = p_debt_id and user_id = v_user for update;
  if not found then
    raise exception 'Utang tidak ditemukan.';
  end if;

  if p_refund then
    v_loan_live := v_debt.transaction_id is not null and v_debt.wallet_id is not null;

    -- Piutang: pinjaman awal kembali MASUK ke dompet â†’ balik dulu.
    if v_loan_live and v_debt.type <> 'payable' then
      perform debt_move_wallet(v_debt.wallet_id, v_debt.amount, v_msg);
    end if;

    -- Cicilan: bayar utang (keluar) â†’ masuk lagi; terima piutang (masuk) â†’ keluar lagi.
    -- Untuk utang ini semua uang MASUK, jadi dijalankan sebelum pinjaman dikeluarkan.
    for v_pay in
      select amount, wallet_id from debt_payments
      where debt_id = v_debt.id and user_id = v_user
        and transaction_id is not null and wallet_id is not null
      order by id
      for update
    loop
      perform debt_move_wallet(
        v_pay.wallet_id,
        case when v_debt.type = 'payable' then v_pay.amount else -v_pay.amount end,
        v_msg
      );
    end loop;

    -- Utang: pinjaman awal (dulu masuk) dikeluarkan lagi â€” paling akhir.
    if v_loan_live and v_debt.type = 'payable' then
      perform debt_move_wallet(v_debt.wallet_id, -v_debt.amount, v_msg);
    end if;
  end if;

  select array_agg(t.id) into v_trx_ids
  from (
    select v_debt.transaction_id as id where v_debt.transaction_id is not null
    union all
    select transaction_id from debt_payments
    where debt_id = v_debt.id and user_id = v_user and transaction_id is not null
  ) t;

  delete from debts where id = v_debt.id;  -- debt_payments ikut via on delete cascade
  if v_trx_ids is not null then
    delete from transactions where user_id = v_user and id = any (v_trx_ids);
  end if;
end $function$
;

CREATE OR REPLACE FUNCTION public.delete_debt_payment(p_payment_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_user uuid := auth.uid();
  v_pay debt_payments%rowtype;
  v_debt debts%rowtype;
  v_into_wallet boolean;
  v_new_remaining numeric;
begin
  if v_user is null then
    raise exception 'Sesi login berakhir. Silakan masuk lagi.';
  end if;

  select * into v_pay from debt_payments where id = p_payment_id and user_id = v_user for update;
  if not found then
    raise exception 'Cicilan tidak ditemukan.';
  end if;
  select * into v_debt from debts where id = v_pay.debt_id and user_id = v_user for update;
  if not found then
    raise exception 'Utang tidak ditemukan.';
  end if;

  v_into_wallet := (v_debt.type = 'receivable');

  -- Membalik efek cicilan: uang yang dulu masuk dikeluarkan lagi, dan sebaliknya.
  if v_pay.transaction_id is not null and v_pay.wallet_id is not null then
    perform debt_move_wallet(
      v_pay.wallet_id,
      case when v_into_wallet then -v_pay.amount else v_pay.amount end,
      'Saldo dompet tidak mencukupi untuk membatalkan pembayaran ini!'
    );
  end if;

  delete from debt_payments where id = v_pay.id;

  if v_pay.transaction_id is not null then
    delete from transactions where id = v_pay.transaction_id and user_id = v_user;
  end if;

  v_new_remaining := v_debt.remaining_amount + v_pay.amount;
  update debts
  set remaining_amount = v_new_remaining,
      status = case when v_new_remaining <= 0 then 'paid' else 'active' end
  where id = v_debt.id;
end $function$
;

CREATE OR REPLACE FUNCTION public.delete_saving_item(p_saving_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_user uuid := auth.uid();
  v_saving savings%rowtype;
  v_marker text := '[SAVING_ID:' || p_saving_id || ']';
  v_trx transactions%rowtype;
  v_delta numeric;
begin
  if v_user is null then raise exception 'Sesi login berakhir. Silakan masuk lagi.'; end if;
  select * into v_saving from savings where id = p_saving_id and user_id = v_user;
  if not found then return; end if;
  perform lock_saving(v_saving.name);
  select * into v_saving from savings where id = p_saving_id and user_id = v_user for update;
  if not found then return; end if;

  select * into v_trx from transactions
  where user_id = v_user and note like '%' || v_marker || '%' and wallet_id is not null
  order by id limit 1 for update;
  if found and exists (select 1 from wallets where id = v_trx.wallet_id and user_id = v_user) then
    v_delta := case when v_saving.amount > 0 then v_trx.amount else -v_trx.amount end;
    perform wallet_spend_guard(v_trx.wallet_id, -v_delta); -- hapus tarikan = uang keluar lagi
    perform wallet_add(v_trx.wallet_id, v_delta);
  end if;

  delete from transactions where user_id = v_user and note like '%' || v_marker || '%';
  delete from savings where id = p_saving_id;
end $function$
;

CREATE OR REPLACE FUNCTION public.delete_transaction(p_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_user uuid := auth.uid();
  v_old transactions%rowtype;
  v_expense boolean;
  v_delta numeric;
begin
  if v_user is null then raise exception 'Sesi login berakhir. Silakan masuk lagi.'; end if;
  select * into v_old from transactions where id = p_id and user_id = v_user for update;
  if not found then return; end if;
  if v_old.note like '%[DEBT_ID:%' then
    raise exception 'Transaksi ini dibuat dari fitur Utang & Piutang. Hapus lewat menu Utang & Piutang.';
  end if;
  select coalesce(is_expense, true) into v_expense from categories where id = v_old.category_id;
  if v_old.wallet_id is not null and exists (select 1 from wallets where id = v_old.wallet_id and user_id = v_user) then
